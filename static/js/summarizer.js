async function triggerGenerateSummary() {
  const textInput = document.getElementById("studyTextInput").value.trim();
  const pdfB64 = AppState.activePdfBase64;
  const model = document.getElementById("summarizerModelSelect").value;
  const btn = document.getElementById("generateSummaryBtn");

  if (!textInput && !pdfB64) {
    alert("Please upload a PDF or enter some study notes text first.");
    return;
  }

  const originalBtnHtml = btn.innerHTML;
  btn.innerHTML = `
    <span class="inline-block animate-spin mr-2">⏳</span>
    <span>Generating Structured Summary...</span>
  `;
  btn.disabled = true;

  try {
    const payload = {
      content: textInput,
      pdf_base64: pdfB64,
      api_key: AppState.apiKey,
      model: model,
      title: "Comprehensive Study Summary",
      source_name: pdfB64 ? "Uploaded PDF" : "Lecture Notes"
    };

    const res = await fetch("/api/summarize", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });

    const data = await res.json();
    if (!res.ok) {
      throw new Error(data.error || "Failed to generate summary");
    }

    AppState.currentSummary = data.summary;
    renderSummaryMarkdown(data.summary);

    if (data.streak) {
      updateStreakDisplay(data.streak);
    }

    playSuccessChime();

    // Scroll to results
    const container = document.getElementById("summaryResultContainer");
    container.classList.remove("hidden");
    container.scrollIntoView({ behavior: "smooth" });

  } catch (err) {
    alert("Summarization Error: " + err.message);
  } finally {
    btn.innerHTML = originalBtnHtml;
    btn.disabled = false;
    if (window.lucide) lucide.createIcons();
  }
}

function renderSummaryMarkdown(markdownText) {
  const container = document.getElementById("summaryMarkdownView");
  if (window.marked) {
    container.innerHTML = marked.parse(markdownText);
  } else {
    // Basic fallback renderer
    container.innerHTML = `<pre class="whitespace-pre-wrap">${markdownText}</pre>`;
  }
}

function copySummaryMarkdown() {
  if (!AppState.currentSummary) return;
  navigator.clipboard.writeText(AppState.currentSummary).then(() => {
    const btnText = document.getElementById("copySummaryBtnText");
    const oldText = btnText.innerText;
    btnText.innerText = "Copied to Clipboard! ✓";
    setTimeout(() => {
      btnText.innerText = oldText;
    }, 2000);
  });
}

