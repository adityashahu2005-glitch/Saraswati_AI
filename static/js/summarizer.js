const SAMPLE_STUDY_NOTES = `Chapter 8: Main Memory & Virtual Memory Management
Operating System Concepts (Core Curriculum)

1. Memory Management Overview:
In modern multi-programming operating systems, main memory (RAM) is a critical resource shared by multiple processes. The CPU fetches instructions from the program counter and executes memory loads/stores. To achieve protection and relocation, the base and limit register hardware verifies every physical address reference.

2. Paging Mechanism:
Paging is a memory management scheme that eliminates the need for contiguous allocation of physical memory.
- Physical memory is broken into fixed-sized blocks called Frames.
- Logical memory is broken into blocks of the same size called Pages.
- Address generated by CPU is divided into:
  * Page number (p): used as an index into a page table which contains the base address of each page in physical memory.
  * Page offset (d): combined with base address to define the physical memory address.
- Paging completely avoids External Fragmentation because any free frame can be allocated to any process page. However, it can incur minor Internal Fragmentation on the final allocated page (average 0.5 * page size).

3. Hardware Acceleration with TLB (Translation Lookaside Buffer):
Standard two-memory-access paging (one for page table entry, one for actual byte) is slow. The TLB is an associative, high-speed hardware cache.
- If page number is in TLB (TLB Hit): Frame number is immediately retrieved.
- If page number is not in TLB (TLB Miss): Memory lookup accesses page table in RAM, then loads frame into TLB.
- Effective Memory Access Time (EMAT):
  EMAT = alpha * (t_TLB + t_mem) + (1 - alpha) * (t_TLB + 2 * t_mem)
  where alpha is the TLB hit ratio.

4. Page Replacement Algorithms & Belady's Anomaly:
When all frames are full and a page fault occurs, the OS must choose a victim page.
- FIFO (First-In-First-Out): Suffers from Belady's Anomaly (allocating more frames can lead to more page faults).
- Optimal (OPT / Belady's): Replaces page that will not be used for longest future period. Theoretical upper bound.
- LRU (Least Recently Used): Replaces page that has not been used for longest past period. Stack algorithm, immune to Belady's Anomaly.

5. Thrashing:
A state where a process spends more time paging than executing instructions. Occurs when sum of working-set sizes of all active processes exceeds available physical memory frames.`;

